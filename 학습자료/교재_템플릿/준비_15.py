def search(question, docs, k=3):
    """질문과 겹치는 두 글자 조각이 많은 문서부터 k건을 돌려줍니다(7장 키워드 검색을 단순하게 줄인 것)"""
    def pieces(text):
        text = re.sub(r'\s+', '', text)
        return {text[i:i + 2] for i in range(len(text) - 1)}
    wanted = pieces(question)
    scored = [(len(wanted & pieces(doc['제목'] + doc['본문'])), doc) for doc in docs]
    return [doc for score, doc in sorted(scored, key=lambda pair: -pair[0])[:k] if score > 0]


def cycle_days(answer):
    """응답에서 "주기: N일"의 N을 꺼냅니다. 없으면 None"""
    found = re.search(r'주기[^\d\n]{0,8}(\d+)\s*일', answer)   # "**주기**: 30일" 같은 강조 표시도 허용
    return int(found.group(1)) if found else None


