P1_YIELD_SOLUTION = '''
# 실습 1 (1) 계산 카드의 정답을 코드로 구합니다
def cumulative_yield(step_yields):
    """단계별 수율(%)의 목록을 받아 누적 수율(%)을 소수 둘째 자리까지 돌려줍니다."""
    total = 1.0
    for step_yield in step_yields:
        total *= step_yield / 100
    return round(total * 100, 2)


correct_yield = cumulative_yield([98.5, 97.2, 99.1, 96.8])
print(f'코드로 구한 정답: {correct_yield}%')
'''

