def practice_cells(solution):
    cells = [md(SOLUTION_INTRO if solution else PRACTICE_INTRO),
             md(SETUP_MD), code(SETUP_KEYS), code(SETUP_COMMON), md(SETUP_AFTER),
             md(P2_MD), code(P2_MATERIAL, '실습2재료'),
             code(P2_SOLUTION if solution else P2_SKELETON, '실습2'),
             code(P2_RUN, '실습2확인')]
    if not solution:
        cells.append(md(P2_ANSWER_MD))
    cells += [md(P3_MD),
              code(P3_COUNT_SOLUTION if solution else P3_COUNT_SKELETON, '실습3표'),
              code(P3_STEP2_SOLUTION if solution else P3_STEP2_SKELETON, '실습3프롬프트'),
              code(P3_RUN, '실습3확인'), code(P3_EXPERIMENT)]
    cells.append(md(P3_EXPLAIN.replace('{RESULT}', RESULT) if solution else P3_ANSWER_MD))
    if not solution:
        cells.append(md(MORE_MD))
    return cells


