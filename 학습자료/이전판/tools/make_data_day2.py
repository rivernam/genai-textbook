def write(rows, prefix, stem, seed):
    rows = list(rows)
    random.Random(seed).shuffle(rows)
    OUT.mkdir(parents=True, exist_ok=True)
    with open(OUT / f'{stem}.csv', 'w', encoding='utf-8-sig', newline='') as inquiry_file, \
            open(OUT / f'{stem}_정답.csv', 'w', encoding='utf-8-sig', newline='') as answer_file:
        inquiries, answers = csv.writer(inquiry_file), csv.writer(answer_file)
        inquiries.writerow(['id', '문의내용'])
        answers.writerow(['id', 'category', 'urgent', '난이도'])
        for number, (text, code, urgent, hard) in enumerate(rows, 1):
            row_id = f'{prefix}{number:03d}'
            inquiries.writerow([row_id, text])
            if code:
                answers.writerow([row_id, NAMES[code], 'true' if urgent else 'false',
                                  '엣지' if hard else '보통'])
    print(f'{stem}: {len(rows)}건')


