def write_receipts(rows, seed):
    rows = list(rows)
    rng = random.Random(seed)
    rng.shuffle(rows)
    with open(OUT / '접수_실습.csv', 'w', encoding='utf-8-sig', newline='') as receipt_file, \
            open(OUT / '접수_실습_정답.csv', 'w', encoding='utf-8-sig', newline='') as answer_file:
        receipts, answers = csv.writer(receipt_file), csv.writer(answer_file)
        receipts.writerow(['id', '접수시각', '본문'])
        answers.writerow(['id', 'team', 'location', 'urgent', '난이도'])
        minutes = sorted(rng.sample(range(5 * 24 * 60), len(rows)))     # 닷새 동안 들어온 접수
        for number, ((text, team, location, urgent, hard), minute) in enumerate(zip(rows, minutes), 1):
            row_id = f'R{number:03d}'
            day, rest = divmod(minute, 24 * 60)
            received = f'2026-11-{9 + day:02d} {rest // 60:02d}:{rest % 60:02d}'
            receipts.writerow([row_id, received, text])
            answers.writerow([row_id, team, location or '', 'true' if urgent else 'false',
                              '엣지' if hard else '보통'])
    print(f'접수_실습: {len(rows)}건')


